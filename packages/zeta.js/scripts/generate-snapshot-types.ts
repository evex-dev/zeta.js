import { resolve } from "node:path";

type Field = { type: string; literalValues?: unknown[]; discriminator?: { property: string; subTypes: { name: string; type: string }[] } };
type Dto = { fields: Record<string, Field>; extends?: string; source: { path: string; line: number }; fieldsComplete: boolean };
type InputField = { type: string; enum?: string; fields?: Record<string, InputField> };
type InputObservation = { method: string; path: string; bodyFields?: Record<string, InputField>; queryFields?: Record<string, InputField> };
type Fixture = { named: Record<string, Dto>; web: Record<string, Dto>; enums: Record<string, Record<string, string | number>>; requestObservations: InputObservation[] };
const fixture = await Bun.file(resolve(import.meta.dir, "fixtures/snapshot-3.51.94-dtos.json")).json() as Fixture;
// These Web-only response exports are tied directly to their saved descriptors.
// The aliases are SDK names, not recovered original class names.
fixture.named.WebBrandpayTermsResponse = fixture.web["export:pF"]!;
fixture.named.WebBrandpayCustomerResponse = fixture.web["export:CC"]!;
const names = new Set(Object.keys(fixture.named));
const typeRef = (name: string): string => name === "Date" ? "string" : name === "JsonNode" ? "JsonValue"
  : names.has(name) ? `SnapshotDtoMap[${JSON.stringify(name)}]` : "unknown";
const lines = [
  "// Generated by scripts/generate-snapshot-types.ts from saved first-party DTOs.",
  "// Properties are optional unless a discriminator proves a literal. Missing",
  "// primitive types and collection cardinality are deliberately not guessed.",
  'import type { JsonValue, JsonObject, QueryParams, QueryValue } from "../core/types.ts";',
  "",
  "/** A decorator identifies the element type, but does not encode cardinality. */",
  "export type SourceValue<T> = T | T[] | null;",
  "",
  "export type SnapshotDtoMap = {",
];
for (const [name, dto] of Object.entries(fixture.named).sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  /** ${dto.source.path}:${dto.source.line}${dto.fieldsComplete ? "" : "; ordinary fields not fully recovered"} */`);
  const parent = dto.extends && names.has(dto.extends) ? `${typeRef(dto.extends)} & ` : "";
  lines.push(`  ${JSON.stringify(name)}: ${parent}{`);
  lines.push("    [key: string]: unknown;");
  for (const [key, field] of Object.entries(dto.fields)) {
    let type: string;
    if (field.type === "literal" && field.literalValues?.length) {
      type = field.literalValues.map((v) => JSON.stringify(v)).join(" | ");
    } else if (field.discriminator) {
      type = field.discriminator.subTypes.map((sub) => `(${typeRef(sub.type)} & { ${JSON.stringify(field.discriminator!.property)}: ${JSON.stringify(sub.name)} })`).join(" | ");
      type = `SourceValue<${type || "unknown"}>`;
    } else {
      type = field.type === "unknown" ? "unknown" : `SourceValue<${typeRef(field.type)}>`;
    }
    lines.push(`    ${JSON.stringify(key)}${field.type === "literal" ? "" : "?"}: ${type};`);
  }
  lines.push("  };", "");
}
lines.push("};", "", "export type SnapshotDtoName = keyof SnapshotDtoMap;", "export type SnapshotDto<Name extends SnapshotDtoName> = SnapshotDtoMap[Name];", "");
function inputShape(fields: Record<string, InputField>, leaf: string): string {
  return `{ ${Object.entries(fields).map(([name, field]) => {
    const type = field.enum && fixture.enums[field.enum] ? `import("./enums.ts").${field.enum}`
      : field.fields ? inputShape(field.fields, leaf) : field.type === "string" ? "string" : leaf;
    return `${JSON.stringify(name)}?: ${type};`;
  }).join(" ")} }`;
}
for (const [name, fieldKey, base, leaf] of [
  ["SnapshotObservedBodyMap", "bodyFields", "JsonObject", "JsonValue"],
  ["SnapshotObservedQueryMap", "queryFields", "QueryParams", "QueryValue"],
] as const) {
  lines.push(`/** Observed input fields; presence in one caller does not prove requiredness. */`, `export type ${name} = {`);
  for (const observation of fixture.requestObservations) {
    const fields = observation[fieldKey];
    if (fields && Object.keys(fields).length) lines.push(`  ${JSON.stringify(`${observation.method} ${observation.path}`)}: ${base} & ${inputShape(fields, leaf)};`);
  }
  lines.push("};", "");
}
const enumLines = ["// Generated from exported enum constants in the saved Zeta 3.51.94 Android DTO module."];
for (const [name, values] of Object.entries(fixture.enums).sort(([a], [b]) => a.localeCompare(b))) {
  enumLines.push(`export const ${name} = ${JSON.stringify(values, null, 2)} as const;`, `export type ${name} = typeof ${name}[keyof typeof ${name}];`, "");
}
for (const [name, text] of [["dtos.ts", lines.join("\n")], ["enums.ts", enumLines.join("\n")]] as const) {
  const target = resolve(import.meta.dir, "../src/generated", name);
  if (Bun.argv.includes("--check")) {
    if (!await Bun.file(target).exists() || await Bun.file(target).text() !== text) throw new Error(`${name} is out of date`);
  } else {
    await Bun.write(target, text);
  }
}
console.log(`Generated ${names.size} source DTO types and ${Object.keys(fixture.enums).length} enums.`);
